/** حداقل طول واژه؛ تک‌حرفی‌ها و دوحرفی‌ها تقریبا همیشه حرف اضافه‌اند. */
const MIN_LENGTH = 3;

export interface Keyword {
  word: string;
  /** در چند پاسخ آمده — نه چند بار، تا تکرار در یک پاسخ آن را بالا نبرد. */
  count: number;
}

/**
 * یکسان‌سازی متن فارسی پیش از شمارش.
 *
 * «کیفيت» با ی عربی و «کیفیت» با ی فارسی دو واژه‌ی متفاوت شمرده می‌شوند
 * مگر اینکه یکسان شوند؛ کاربر هر دو را با یک صفحه‌کلید متفاوت می‌نویسد.
 * نیم‌فاصله هم به فاصله تبدیل می‌شود تا «می‌شود» و «می شود» یکی شوند.
 */
export function normalizePersian(text: string): string {
  return (
    text
      .replace(/[يى]/g, 'ی')
      .replace(/ك/g, 'ک')
      .replace(/[آأإ]/g, 'ا')
      .replace(/ة/g, 'ه')
      // اعراب و کشیده
      .replace(/[ً-ْـ]/g, '')
      // نیم‌فاصله و فاصله‌های عرض‌صفر
      .replace(/[\u200B-\u200D\u2060]/g, ' ')
      // ارقام فارسی و عربی به لاتین
      .replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))
      .replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
  );
}

/**
 * پرتکرارترین کلیدواژه‌های مجموعه‌ای از پاسخ متنی.
 *
 * @param limit بیشترین تعداد کلیدواژه‌ی برگشتی.
 */
export function extractKeywords(texts: string[], limit = 20): Keyword[] {
  const counts = new Map<string, number>();

  for (const text of texts) {
    // مجموعه، نه آرایه: تکرار یک واژه در یک پاسخ نباید آن را بالا ببرد،
    // وگرنه یک نفر پرحرف کل نمودار را تعیین می‌کند.
    const seen = new Set<string>();

    for (const raw of normalizePersian(String(text)).split(/[^\p{L}\p{N}]+/u)) {
      const word = raw.trim();
      if (word.length < MIN_LENGTH) continue;
      if (STOP_WORDS.has(word)) continue;
      // واژه‌ی تماماً عددی چیزی درباره‌ی موضوع نمی‌گوید.
      if (/^\d+$/.test(word)) continue;
      seen.add(word);
    }

    for (const word of seen) {
      counts.set(word, (counts.get(word) ?? 0) + 1);
    }
  }

  return [...counts.entries()]
    .filter(([, count]) => count > 1 || texts.length < 5)
    .map(([word, count]) => ({ word, count }))
    .sort((a, b) => b.count - a.count || a.word.localeCompare(b.word))
    .slice(0, limit);
}
