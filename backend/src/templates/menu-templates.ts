import type { MenuSection } from '../database/entities/menu.entity';

export interface MenuTemplate {
  key: string;
  title: string;
  /** یک خط توضیح، برای انتخاب در پنل. */
  summary: string;
  icon: string;
  category: string;
  description: string;
  sections: MenuSection[];
}

/**
 * قالب آماده‌ی منو.
 *
 * قیمت‌ها عمدا خالی‌اند: عدد نمونه اگر جا بماند، روی میز مهمان چاپ می‌شود و
 * آبروی کسب‌وکار را می‌برد. نام و چیدمان اقلام پر است تا کار از صفر شروع
 * نشود و فقط قیمت‌ها وارد شوند.
 */
const t = (
  id: string,
  name: string,
  description = '',
): { id: string; name: string; description: string; price: string } => ({
  id,
  name,
  description,
  price: '',
});

const section = (
  id: string,
  title: string,
  items: Array<{
    id: string;
    name: string;
    description: string;
    price: string;
  }>,
): MenuSection => ({ id, title, items });

