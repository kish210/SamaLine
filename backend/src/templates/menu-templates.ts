export function findMenuTemplate(key: string): MenuTemplate | undefined {
  return MENU_TEMPLATES.find((template) => template.key === key);
}

/** فراداده‌ی قالب‌ها برای انتخاب در پنل؛ بدون خودِ محتوا. */
export function menuTemplateSummaries() {
  return MENU_TEMPLATES.map((template) => ({
    key: template.key,
    title: template.title,
    summary: template.summary,
    icon: template.icon,
    category: template.category,
    itemCount: template.sections.reduce((n, s) => n + s.items.length, 0),
  }));
}
